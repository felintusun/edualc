#!/usr/bin/env python3
"""Writes the presentation model from the window's Slint types, for every frontend to share.

From `ui/types.slint` (its enums and structs) and `ui/state.slint` (its globals' `in`
properties), it writes:

- `crates/core/src/present/model.rs`: the same types as plain Rust data, which the app's presenter fills and
  every frontend (the Slint window, the Dioxus page) shows;
- `crates/slint/src/ui/model.rs`: the Slint window's side, which turns them into Slint's types and brings a
  global in line with a new state, setting only what changed and changing list models row by row
  (a row that stays keeps its selection and what was typed into it).

Run it from the repository's root after changing either file; both outputs are committed.
"""

import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
TYPES = (ROOT / "ui/types.slint").read_text()
STATE = (ROOT / "ui/state.slint").read_text()

# Globals whose state the presenter owns; the others are the window's own.
GLOBALS = ["Session", "Composer", "Sessions", "Prompt", "Peek", "Side",
           "Preferences", "Usage"]
# What isn't state: the transcript's rows, which change one by one (`TranscriptChange`), and
# the window's own counters, bumped through `Command`s.
SKIPPED = {
    ("Transcript", "entries"),
    ("Transcript", "scroll-to-end-serial"),
    ("Transcript", "opened-serial"),
    ("Composer", "focus-serial"),
    ("Side", "focus-serial"),
    ("Sessions", "opened-serial"),
}


def camel(name):
    return "".join(part[:1].upper() + part[1:] for part in name.split("-"))


def snake(name):
    return name.replace("-", "_")


def strip_comments(text):
    return re.sub(r"//[^\n]*", "", text)


enums = {}
for match in re.finditer(r"export enum (\w+) \{([^}]*)\}", strip_comments(TYPES)):
    enums[match.group(1)] = [v.strip() for v in match.group(2).split(",") if v.strip()]

structs = {}
for match in re.finditer(r"export struct (\w+) \{([^}]*)\}", strip_comments(TYPES)):
    fields = []
    for line in re.split(r"[,;]", match.group(2)):
        line = line.strip()
        if not line:
            continue
        name, kind = (part.strip() for part in line.split(":", 1))
        fields.append((name, kind))
    structs[match.group(1)] = fields

globals_ = {}
for match in re.finditer(r"export global (\w+) \{(.*?)\n\}", strip_comments(STATE), re.S):
    name = match.group(1)
    if name not in GLOBALS:
        continue
    fields = []
    for prop in re.finditer(r"(?<![-\w])in property <([^>]+)> ([\w-]+)", match.group(2)):
        if (name, prop.group(2)) in SKIPPED:
            continue
        fields.append((prop.group(2), prop.group(1)))
    globals_[name] = fields

SCALARS = {"string": "String", "int": "i32", "float": "f32", "length": "f32", "bool": "bool",
           "styled-text": "Styled", "image": "Image"}


def rust_type(kind):
    if kind.startswith("[") and kind.endswith("]"):
        return f"Vec<{rust_type(kind[1:-1])}>"
    if kind in SCALARS:
        return SCALARS[kind]
    if kind in enums or kind in structs:
        return kind
    sys.exit(f"unknown Slint type {kind}")


def has_float(kind, seen=()):
    if kind.startswith("["):
        return has_float(kind[1:-1], seen)
    if kind in ("float", "length"):
        return True
    if kind in structs and kind not in seen:
        return any(has_float(k, seen + (kind,)) for _, k in structs[kind])
    return False


def derives(fields, default=True):
    eq = not any(has_float(kind) for _, kind in fields)
    items = ["Debug", "Clone"] + (["Default"] if default else []) + ["PartialEq"]
    if eq:
        items.append("Eq")
    items += ["serde::Serialize", "serde::Deserialize"]
    return f"#[derive({', '.join(items)})]"


out = ['''// @generated by scripts/present_gen.py from ui/types.slint and ui/state.slint: run it again
// rather than editing this file.

//! What the window shows, as plain data: the same types as the Slint window's, which every
//! frontend shows.

use super::{Image, Styled};
''']
for name, variants in enums.items():
    out.append(f"#[derive(Debug, Clone, Copy, Default, PartialEq, Eq, Hash, serde::Serialize, serde::Deserialize)]\npub enum {name} {{")
    for index, variant in enumerate(variants):
        if index == 0:
            out.append("    #[default]")
        out.append(f"    {camel(variant)},")
    out.append("}\n")
for name, fields in structs.items():
    out.append(derives(fields))
    out.append(f"pub struct {name} {{")
    for field, kind in fields:
        out.append(f"    pub {snake(field)}: {rust_type(kind)},")
    out.append("}\n")
for name, fields in globals_.items():
    out.append(f"/// The `{name}` global's state.")
    out.append(derives(fields))
    out.append(f"pub struct {name} {{")
    for field, kind in fields:
        out.append(f"    pub {snake(field)}: {rust_type(kind)},")
    out.append("}\n")
(ROOT / "crates/core/src/present/model.rs").write_text("\n".join(out))

# The Slint side.
slint = ['''// @generated by scripts/present_gen.py from ui/types.slint and ui/state.slint: run it again
// rather than editing this file.

//! The presentation model as Slint's types, and the window's globals brought in line with it.

use slint::ComponentHandle;

use super::{Drawing, ToSlint, md_body, resync};
use crate::generated::{self as slint_ui, AppWindow};
use crate::present::model as present;
''']
for name, variants in enums.items():
    slint.append(f"impl ToSlint for present::{name} {{\n    type Slint = slint_ui::{name};\n    fn to_slint(&self, _: &Drawing) -> Self::Slint {{\n        match self {{")
    for variant in variants:
        slint.append(f"            Self::{camel(variant)} => slint_ui::{name}::{camel(variant)},")
    slint.append("        }\n    }\n}\n")


# Fields the Slint window draws in its own way, by a function of `ui/mod.rs`: a text block's
# paragraphs, which Slint draws with no space between them, and a code block's colours.
DRAWN_BY_THE_WINDOW = {("MdBlock", "body")}


def is_list(kind):
    return kind.startswith("[")


for name, fields in structs.items():
    slint.append(f"impl ToSlint for present::{name} {{\n    type Slint = slint_ui::{name};\n    fn to_slint(&self, images: &Drawing) -> Self::Slint {{\n        slint_ui::{name} {{")
    for field, kind in fields:
        if (name, field) in DRAWN_BY_THE_WINDOW:
            slint.append(f"            {snake(field)}: md_body(self, images),")
        else:
            slint.append(f"            {snake(field)}: self.{snake(field)}.to_slint(images),")
    slint.append("        }\n    }")
    # A row brought in line in place: its lists keep their models.
    if any(is_list(kind) for _, kind in fields):
        slint.append(f"    fn sync(&self, old: &Self, shown: Self::Slint, images: &Drawing) -> Self::Slint {{")
        slint.append("        let mut row = self.to_slint(images);")
        for field, kind in fields:
            if is_list(kind):
                f = snake(field)
                slint.append(f"        row.{f} = resync(&shown.{f}, &old.{f}, &self.{f}, images).unwrap_or(shown.{f});")
        slint.append("        row\n    }\n}\n")
    else:
        slint.append("}\n")

for name, fields in globals_.items():
    slint.append(f"/// Brings the `{name}` global in line with `new`, setting what differs from `old` (all,\n/// for none).")
    slint.append(f"pub(super) fn apply_{snake(name).lower()}(window: &AppWindow, old: Option<&present::{name}>, new: &present::{name}, images: &Drawing) {{")
    slint.append(f"    let global = window.global::<slint_ui::{name}>();")
    for field, kind in fields:
        f = snake(field)
        if is_list(kind):
            slint.append(f"    match old {{\n        Some(old) if old.{f} != new.{f} => {{\n            if let Some(model) = resync(&global.get_{f}(), &old.{f}, &new.{f}, images) {{\n                global.set_{f}(model);\n            }}\n        }}\n        Some(_) => {{}}\n        None => global.set_{f}(new.{f}.to_slint(images)),\n    }}")
        else:
            slint.append(f"    if old.is_none_or(|old| old.{f} != new.{f}) {{\n        global.set_{f}(new.{f}.to_slint(images));\n    }}")
    slint.append("}\n")
(ROOT / "crates/slint/src/ui/model.rs").write_text("\n".join(slint))
print("wrote crates/core/src/present/model.rs and crates/slint/src/ui/model.rs")
